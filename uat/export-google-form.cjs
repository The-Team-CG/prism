// Produce the paste-ready Apps Script file and the readable question bank from uat-test-cases.gs,
// without external dependencies. Both outputs are generated; edit uat-test-cases.gs instead.
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');

const read = (name) => fs.readFileSync(path.join(__dirname, name), 'utf8');

function googleFormScript() {
  const contents = ['uat-test-cases.gs', 'build-uat-form.gs'].map(read);
  return '// Paste this entire file into Code.gs at https://script.google.com/home/start\n' +
    '// Run buildUatForm. See uat/README.md.\n\n' + contents.join('\n\n');
}

function loadBank() {
  const context = vm.createContext({});
  vm.runInContext(read('uat-test-cases.gs'), context);
  return vm.runInContext('UAT_FORM', context);
}

const cell = (text) => String(text).replace(/\|/g, '\\|').replace(/\r?\n/g, ' ');

function questionBank(bank = loadBank()) {
  const roles = bank.roles;
  const count = (role) => role.modules.reduce((sum, module) => sum + module.cases.length, 0);
  const lines = [
    '# P.R.I.S.M UAT question bank',
    '',
    'Source: `uat-test-cases.gs`. Create one Google Form with the paste-ready `PRISM-UAT-Google-Form.gs`. See [setup instructions](README.md). This file is generated by `node uat/export-google-form.cjs`; do not edit it by hand.',
    '',
    '## Form flow',
    '',
    `1. **What is your user role?** ${roles.slice(0, -1).map((role) => role.name).join(', ')}, or ${roles.at(-1).name}.`,
    "2. **What module would you test?** Only that role's modules are listed.",
    '3. Read the setup, steps, and expected results below. Each module has one required ratings grid with one row per test case and four columns:',
    '   - Passed - Working',
    '   - Partially Passed - Works but needs revision (w/ comment)',
    '   - Fail - Not Working',
    '   - Skipped - Di tinest (w/ comment)',
    '4. Complete the required module comment box:',
    '',
    '   > IF YOU SELECT PARTIALLY PASSED OR SKIPPED Please may we know your suggestion or the part that need to improve STRICTLY',
    '   >',
    '   > Format: Test Case ID - Comment',
    '',
    '   Use one line per Partially Passed or Skipped case. The form validates the ID and comment format; reviewers check each relevant rating has its own comment. If none apply, use a case ID from the module followed by ` - No revision or skipped-case comment needed.`',
    '5. Enter tester name and test date at the end, then submit. **One submission per module.** Use Submit another response for your next module.',
    '',
    '## Summary',
    '',
    '| Role | Modules | Test cases |',
    '| --- | ---: | ---: |',
    ...roles.map((role) => `| ${role.name} | ${role.modules.length} | ${count(role)} |`),
    `| **Total** | **${roles.reduce((sum, role) => sum + role.modules.length, 0)}** | **${roles.reduce((sum, role) => sum + count(role), 0)}** |`,
  ];
  for (const role of roles) {
    lines.push('', `## ${role.name}`, '', role.signIn);
    for (const module of role.modules) {
      lines.push('', `### ${module.id} · ${module.name}`, '', `Before you start: ${module.setup}`, '',
        '| ID | Test case | Steps | Expected result |', '| --- | --- | --- | --- |',
        ...module.cases.map((tc) => `| ${tc.id} | ${cell(tc.title)} | ${cell(tc.steps)} | ${cell(tc.expected)} |`));
    }
  }
  return lines.join('\n') + '\n';
}

module.exports = { googleFormScript, questionBank };

if (require.main === module) {
  fs.writeFileSync(path.join(__dirname, 'PRISM-UAT-Google-Form.gs'), googleFormScript());
  console.log('Created uat/PRISM-UAT-Google-Form.gs');
  fs.writeFileSync(path.join(__dirname, 'UAT-question-bank.md'), questionBank());
  console.log('Created uat/UAT-question-bank.md');
}
