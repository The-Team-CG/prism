const TOTP_PERIOD_SECONDS = 30;
const TOTP_DIGITS = 6;
const BASE32_ALPHABET = 'ABCDEFGHIJKLMNOPQRSTUVWXYZ234567';

function base32Decode(value) {
  let bits = 0;
  let buffer = 0;
  const bytes = [];

  for (const character of value.replace(/=+$/, '').toUpperCase()) {
    const index = BASE32_ALPHABET.indexOf(character);
    if (index < 0) throw new Error('Invalid TOTP secret');
    buffer = (buffer << 5) | index;
    bits += 5;
    if (bits >= 8) {
      bytes.push((buffer >>> (bits - 8)) & 255);
      bits -= 8;
    }
  }
  return Buffer.from(bytes);
}

function totpCodeAt(secret, counter) {
  const key = base32Decode(secret);
  const counterBuffer = Buffer.alloc(8);
  counterBuffer.writeBigUInt64BE(BigInt(counter));
  const digest = createHmac('sha1', key).update(counterBuffer).digest();
  const offset = digest[digest.length - 1] & 0x0f;
  const binary = ((digest[offset] & 0x7f) << 24)
    | ((digest[offset + 1] & 0xff) << 16)
    | ((digest[offset + 2] & 0xff) << 8)
    | (digest[offset + 3] & 0xff);
  return String(binary % 1_000_000).padStart(TOTP_DIGITS, '0');
}

function currentTotpCode(secret, nowMs = Date.now()) {
  return totpCodeAt(secret, Math.floor(nowMs / 1000 / TOTP_PERIOD_SECONDS));
}

async function request(path, init = {}) {
  const response = await fetch(`${baseUrl}${path}`, {
    ...init,
    headers: {
      ...jsonHeaders,
      ...(bearerToken ? { Authorization: `Bearer ${bearerToken}` } : {}),
      ...(init.headers ?? {}),
    },
  });

  const contentType = response.headers.get('content-type') ?? '';
  const body = contentType.includes('application/json')
    ? await response.json()
    : await response.text();

  return { response, body };
}

async function expectOk(label, path, init = {}) {
  const { response, body } = await request(path, init);

  if (!response.ok) {
    throw new Error(`${label} failed: ${response.status} ${JSON.stringify(body)}`);
  }

  console.log(`ok ${label}`);
  return body?.data ?? body;
}

async function expectBadRequest(label, path, init = {}) {
  const { response, body } = await request(path, init);

  if (response.status !== 400) {
    throw new Error(`${label} expected 400: ${response.status} ${JSON.stringify(body)}`);
  }

  console.log(`ok ${label}`);
  return body;
}

async function expectForbidden(label, path, init = {}) {
  const { response, body } = await request(path, init);

  if (response.status !== 403) {
    throw new Error(`${label} expected 403: ${response.status} ${JSON.stringify(body)}`);
  }

  console.log(`ok ${label}`);
  return body;
}

